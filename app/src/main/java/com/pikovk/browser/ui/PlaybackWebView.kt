package com.pikovk.browser.ui

import android.content.Context
import android.view.View
import android.webkit.WebView
import com.pikovk.browser.util.Prefs

// WebView, который при выключенном экране / свёрнутом приложении сообщает
// Chromium, что он ПО-ПРЕЖНЕМУ НА ЭКРАНЕ (1.3.18).
//
// Почему это было последним недостающим звеном перехода «трек за треком».
// Снапшот сети из полной версии vk.ru/audio (08.11.2026, музыка_web.har)
// показал точный протокол автоперехода плеера VK: примерно за 11 секунд до
// конца трека JS подкачивает начало следующего (Range-запрос к CDN), в момент
// окончания — цепочка из 4-6 сетевых вызовов за ~1 секунду (listened_data,
// ad_event, start_playback, al_audio.php за ссылкой, новое соединение с CDN).
// Вся цепочка построена на JS-таймерах: и предзагрузка, и шаги перехода
// срабатывают по setTimeout.
//
// 1.3.14 держал живыми процесс рендерера (приоритет), процессор (wake-lock)
// и сеть (исключение из Doze) — но страница при этом «знала», что она
// невидима: когда активность уходит с экрана, WebView получает событие
// смены видимости окна, и Chromium включает для скрытой страницы режим
// экономии: сначала подвешивает кадровую отрисовку, через ~5 минут —
// жёсткий троттлинг таймеров (не чаще одного пробуждения в минуту),
// при нехватке памяти страницу можно заморозить целиком. Аудиотракт при
// этом живёт своей жизнью — текущий трек доигрывает до конца буфера,
// а дальше молчание: цепочка перехода либо стоит в очереди троттлинга,
// либо не стартует вовсе. Отсюда точный симптом владельца: «оно и не
// прекращалось прерываться — просто трек за треком не идут», при этом
// руками (тапом) треки переключаются — обработчик клика не таймер.
//
// Решение — классика WebView-плееров: не пускать в Chromium сигнал
// «страница скрыта». Пока включён тумблер «Фоновое воспроизведение»,
// любое событие смены видимости окна переотправляется наверх как
// VISIBLE: таймеры работают на полной скорости, предзагрузка следующего
// трека и цепочка перехода выполняются в реальном времени, как на экране.
// Плата — страница в фоне продолжает считать себя видимой (немного выше
// расход батареи); тумблер это покрывает: выключишь фон — сигнал
// видимости снова честный.
//
// Сигнал берётся из Prefs на каждый вызов (а не один раз при создании):
// переключение тумблера в настройках действует без пересборки WebView.
class PlaybackWebView(context: Context) : WebView(context) {

    override fun onWindowVisibilityChanged(visibility: Int) {
        if (Prefs.backgroundPlayback) {
            super.onWindowVisibilityChanged(View.VISIBLE)
        } else {
            super.onWindowVisibilityChanged(visibility)
        }
    }

    // 1.3.23: дублируем подмену и на уровне диспетчера. На части прошивок
    // сигнал видимости доходит до WebView не напрямую, а только по цепочке
    // dispatchWindowVisibilityChanged от корня иерархии — переопределение
    // одной лишь точки onWindowVisibilityChanged оставляло дыру, через
    // которую Chromium узнавал о скрытии страницы и троттлил её таймеры.
    override fun dispatchWindowVisibilityChanged(visibility: Int) {
        if (Prefs.backgroundPlayback) {
            super.dispatchWindowVisibilityChanged(View.VISIBLE)
        } else {
            super.dispatchWindowVisibilityChanged(visibility)
        }
    }
}
